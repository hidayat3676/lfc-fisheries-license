    private function resolveDistrict(string $rawDistrict): District
    {
        $key = strtolower(trim($rawDistrict));
        $canonicalName = self::DISTRICT_ALIASES[$key] ?? trim($rawDistrict);

        $district = District::query()
            ->whereRaw('LOWER(name) = ?', [strtolower($canonicalName)])
            ->first();

        if (! $district) {
            $district = District::query()->create([
                'name' => $canonicalName,
                'code' => strtoupper(str_replace(['.', ' ', '-', '/', '(', ')'], '', $canonicalName)),
                'is_active' => true,
            ]);
        }

        return $district;
    }


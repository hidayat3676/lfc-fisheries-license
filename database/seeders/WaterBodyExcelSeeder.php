    public function run(): void
    {
        $hasLicenseTypeColumn = Schema::hasColumn('reservoirs', 'license_type');
        $hasImagePathColumn = Schema::hasColumn('reservoirs', 'image_path');
        $rows = $this->excelWaterBodies();

        DB::transaction(function () use ($rows, $hasLicenseTypeColumn, $hasImagePathColumn) {
            foreach ($rows as $index => $item) {
                $district = $this->resolveDistrict($item['district']);

                $office = Office::query()->updateOrCreate(
                    [
                        'district_id' => $district->id,
                        'name' => 'District Officer Fisheries '.$district->name,
                    ],
                    [
                        'is_active' => true,
                    ]
                );

                $lat = $item['latitude'] ?? $item['start_lat'] ?? null;
                $lng = $item['longitude'] ?? $item['start_lng'] ?? null;

                $payload = [
                    'office_id' => $office->id,
                    'water_body_type' => $item['water_body_type'] ?? 'river',
                    'trout_type' => $item['trout_type'] ?? 'non_trout',
                    'latitude' => $lat,
                    'longitude' => $lng,
                    'start_lat' => $item['start_lat'] ?? $lat,
                    'start_lng' => $item['start_lng'] ?? $lng,
                    'end_lat' => $item['end_lat'] ?? null,
                    'end_lng' => $item['end_lng'] ?? null,
                    'coordinates_raw' => $item['coordinates_raw'] ?? null,
                    'length_km_notes' => $item['length_km_notes'] ?? null,
                    'directions_url' => ($lat !== null && $lng !== null)
                        ? 'https://www.google.com/maps?q='.$lat.','.$lng
                        : null,
                    'is_open_for_licensing' => true,
                    'is_active' => true,
                    'source_file' => 'district_wise_water_bodies_excel',
                ];

                if ($hasLicenseTypeColumn) {
                    $payload['license_type'] = $item['license_type'];
                }

                $existing = Reservoir::query()
                    ->where('district_id', $district->id)
                    ->where('name', $item['name'])
                    ->first();

                if ($hasImagePathColumn && (! $existing || empty($existing->image_path))) {
                    $payload['image_path'] = $this->defaultPhotoUrl(
                        $item['water_body_type'] ?? 'river',
                        $item['trout_type'] ?? 'non_trout',
                        $index
                    );
                }

                Reservoir::query()->updateOrCreate(
                    [
                        'district_id' => $district->id,
                        'name' => $item['name'],
                    ],
                    $payload
                );
            }
        });
    }

